const KEY = 'cn:lang';
const FALLBACK = 'en';
const SUPPORTED = Object.keys(I18N);

let CURRENT = null;

async function __cnNow() {
  let lang;
  try {
    const s = await chrome.storage.local.get(KEY);
    lang = s[KEY];
  } catch (e) {
    lang = undefined;
  }
  if (typeof lang !== 'string' || !SUPPORTED.includes(lang)) {
    lang = (typeof navigator !== 'undefined' && navigator.language ? navigator.language : 'en').toLowerCase().split('-')[0];
    if (!SUPPORTED.includes(lang)) lang = FALLBACK;
  }
  return lang;
}

function __cnDict(lang) {
  return I18N[lang] || I18N[FALLBACK];
}

function __cnT(key, lang, params) {
  const d = __cnDict(lang || CURRENT || FALLBACK);
  let v = d[key];
  if (typeof v !== 'string') v = I18N[FALLBACK][key] || key;
  if (params && typeof params === 'object') {
    for (const k of Object.keys(params)) v = v.split('{{' + k + '}}').join(String(params[k]));
  }
  return v;
}

async function __cnApply(root) {
  CURRENT = await __cnNow();
  const d = __cnDict(CURRENT);
  root = root || document;
  for (const el of root.querySelectorAll('[data-i18n]')) {
    const k = el.getAttribute('data-i18n');
    let v = d[k];
    if (typeof v !== 'string') v = I18N[FALLBACK][k] || k;
    let t = el.tagName.toLowerCase();
    if (t === 'input' || t === 'textarea') el.placeholder = v;
    else el.textContent = v;
  }
  const langSel = root.querySelector('[data-i18n-lang]');
  if (langSel) {
    langSel.value = CURRENT;
    langSel.addEventListener('change', async () => {
      await chrome.storage.local.set({ [KEY]: langSel.value });
      CURRENT = langSel.value;
      await __cnApply(root);
    });
  }
  const title = root.querySelector('title');
  if (title && d.name) title.textContent = d.name;
  return d;
}

window.__cnDict = __cnDict;
window.__cnT = __cnT;
window.__cnNow = __cnNow;
